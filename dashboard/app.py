st.markdown(r"""
## Итоги и рекомендации

### Состояние продукта

Ключевые показатели в начале дашборда дают общую картину состояния платформы: сколько вопросов решают пользователи, какова средняя точность ответов и какое количество ответов приходит на вопросы.

Эти показатели можно использовать как базовые метрики и отслеживать, как они меняются после продуктовых изменений.

### Где мы теряем пользователей?

Два графика retention позволяют посмотреть на отток с двух сторон: по времени и по количеству решённых вопросов.

**Если максимальный отток происходит в первые дни**, пользователю важно быстрее показать ценность продукта. В таком случае стоит улучшать первое знакомство с платформой, давать короткие достижимые цели, стартовые задания, бонусы за первые дни обучения и раннюю геймификацию.

**Если пользователи уходят спустя продолжительное время**, проблема может быть связана уже не с первым знакомством, а с потерей мотивации. Тогда стоит использовать контрольные точки, серии занятий, рейтинги, достижения, ежедневные цели и систему бонусных очков.

**Если сильный отток наблюдается после небольшого количества вопросов**, стоит сделать первые задания более понятными и постепенно увеличивать их сложность.

**Если отток происходит после большого количества решённых вопросов**, пользователю может не хватать нового контента или ощущения дальнейшего прогресса. В таком случае можно добавлять новые вопросы, дополнительные активности и более сложные траектории обучения.

**Главное**: на каждом графике видно место, в котором происходит основной отток пользователей, как по дням, так и по вопросам, поэтому именно на этот вопрос и/или на следующий нужно поставить особую контрольную точку, которая подарит дополнительные баллы в рейтинговую систему, даст особую и актуальную акцию и так далее.

### Как меняется успешность?

График точности показывает, как успешность связана с длительностью обучения.

**Если после некоторого периода точность выходит на плато**, простое увеличение количества решённых вопросов перестаёт заметно улучшать результат.

В таком случае пользователю стоит предлагать не больше однотипных заданий, а другие способы обучения:

- перерешивание вопросов;
- дорешивание пропущенных заданий;
- повторение ошибок;
- тематические подборки;
- дополнительные активности.

**Если точность продолжает расти**, важно поддерживать текущую траекторию и мотивировать пользователя продолжать регулярное обучение.

### Какие темы требуют внимания?

Топ самых сложных тем показывает, где пользователи систематически совершают больше ошибок.

**Если тема стабильно входит в число самых сложных**, стоит не только добавлять новые вопросы, но и улучшать обучение перед ними:

- давать краткие конспекты;
- добавлять дополнительные объяснения;
- показывать примеры решений;
- давать возможность повторного решения;
- создавать карточки и упражнения для повторения материала.

### Что говорит скорость ответа?

Соотношение быстрых и медленных неправильных ответов может помочь определить разные причины ошибок.

**Если преобладают быстрые неправильные ответы**, пользователи могут отвечать слишком поспешно. В таком случае можно проверить идею минимального времени до возможности отправить ответ или другие механики, которые стимулируют сначала подумать.

**Если преобладают медленные неправильные ответы**, пользователи могут слишком долго застревать на вопросах. Тогда можно добавить ограничение максимального времени, подсказки после определённого интервала или возможность перейти к объяснению и вернуться к вопросу позже.

В любом случае, если есть где либо преобладание правильных ответов в одной из временных групп над другим, то стоит ввести мотивирующий таймер: например, если медленные отвечают лучше быстрых, то дать быстрым блок таймером на ответ, чтобы они собрались с мыслями и перепроверили ответ. В обратном случае - надо дать медленным таймер на более быстрый ответ. Таймер в данном случае абстрактный - он может быть как реальный отсчет времени, а может быть как бонус за дополнительные баллы, если пользователь подольше подумает/быстрее даст ответ

В обоих случаях можно дополнительно мотивировать правильные ответы системой очков, серий и достижений.

### Как использовать лекции?

**Если по отдельным темам точность после просмотра лекции заметно выше**, такие лекции можно активнее рекомендовать пользователям перед сложными заданиями.

**Если просмотр лекции почти не связан с улучшением результата**, стоит проверить её содержание и качество: переработать материал, добавить примеры или изменить формат.

**Если сложная тема плохо покрыта лекциями**, это сигнал для создания новой лекции, конспекта или другого вспомогательного материала.

---

### Что делать дальше?

Стратегия продукта должна зависеть от того, где именно возникает проблема:

- ранний отток → улучшать первые шаги пользователя;
- поздний отток → усиливать долгосрочную мотивацию и геймификацию;
- плато точности → переходить от количества заданий к повторению и новым форматам обучения;
- сложные темы → добавлять конспекты, объяснения, лекции и возможность перерешивания;
- быстрые ошибки → стимулировать пользователя подумать перед ответом;
- медленные ошибки → помогать пользователю не застревать на заданиях;
- нехватка дальнейшего контента → добавлять новые вопросы и дополнительные активности.
""")
